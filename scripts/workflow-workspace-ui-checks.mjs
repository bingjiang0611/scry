import assert from 'node:assert/strict'
import { writeFile } from 'node:fs/promises'
import { join } from 'node:path'
import { tmpdir } from 'node:os'

export async function checkWorkflowWorkspace({ read, wait, click, win }) {
  await wait('document.body.dataset.workflowFixtureRender !== undefined')
  await read('window.workflowFixture.installWorkspace()')
  await wait('document.querySelector("[data-workflow-workspace-open]") && !document.querySelector("[data-workflow-action=plan]")')
  const before = await read('structuredClone(window.workflowFixture.counters)')
  const composer = await read('document.querySelector("#parent-composer").value')
  await click('[data-workflow-workspace-open]')
  await wait('document.querySelector("[data-workflow-classifier-result=classifier_record_0]") && document.querySelector("[data-workflow-flow-node=classifier_flag]")?.dataset.state === "completed"')
  assert.equal(await read('document.querySelectorAll("[data-workflow-workspace-code]").length'), 32)
  assert.equal(await read('document.querySelectorAll("[data-workflow-flow-node]").length'), 32)
  assert.equal(await read('document.querySelectorAll("[data-workflow-flow-edge]").length'), 31)
  assert.equal(await read('window.workflowFixture.workspaceFrameQueries().length'), 0, 'canvas opening must not eagerly inspect frame details')
  await click('[data-workflow-inspection-frame=classifier_frame_0]')
  await wait('document.querySelector("[data-workflow-frame=classifier_frame_0]")')
  assert.deepEqual(await read('window.workflowFixture.workspaceFrameQueries()'), ['classifier_frame_0'], 'one user-requested frame must cause one canonical frame read')
  await click('[data-workflow-frame-action=close]')
  await wait('!document.querySelector("[data-workflow-frame=classifier_frame_0]")')
  assert.equal(await read('document.querySelector(".workflow-workspace-state").dataset.state'), 'blocked')
  const proof = () => read('Array.from(document.querySelectorAll(".workflow-classifier-result dd"), node => node.textContent)')
  const flag = await proof()
  assert.deepEqual(flag.slice(0, 2), ['false', '0.98'])
  assert.deepEqual(JSON.parse(flag[2]), { true: 0.02, false: 0.98 })
  assert.match(flag[3], /用量：部分.*输入 8.*输出 1.*费用未提供/)
  const paused = await read('Array.from(document.querySelectorAll(".workflow-workspace-runtime-controls button"), node => ({text:node.textContent,disabled:node.disabled}))')
  assert.equal(paused.find(node => node.text.includes('暂停')).disabled, true)
  assert.equal(paused.find(node => node.text.includes('重启')).disabled, true)
  await click('[data-workflow-workspace-code=classifier_zero]')
  await wait('document.querySelector("[data-workflow-classifier-result=classifier_record_1]")')
  assert.equal(await read('document.querySelector("[data-workflow-flow-node=classifier_zero]").getAttribute("aria-pressed")'), 'true')
  assert.deepEqual(await proof(), ['0', '0', '未提供', '用量：未提供'], 'zero is data, not a missing-value fallback')
  await click('[data-workflow-flow-node=classifier_missing]')
  await wait('document.querySelector("[data-workflow-classifier-result=classifier_record_2]")')
  assert.equal(await read('document.querySelector("[data-workflow-workspace-code=classifier_missing]").getAttribute("aria-pressed")'), 'true')
  assert.deepEqual(await proof(), ['未提供', '未提供', '未提供', '用量：未提供'])
  assert.equal(await read('document.querySelector("[data-workflow-flow-node=classifier_missing]").dataset.state'), 'unknown')
  await click('[data-workflow-workspace-page=next]')
  await wait('document.querySelector("[data-workflow-workspace-code=call_34]")')
  assert.equal(await read('document.querySelectorAll("[data-workflow-workspace-code]").length'), 9)
  assert.equal(await read('document.querySelectorAll("[data-workflow-flow-node]").length'), 9)
  assert.equal(await read('document.querySelectorAll("[data-workflow-flow-edge]").length'), 0, 'off-page parents must not become fabricated edges')
  await click('[data-workflow-flow-node=call_34]')
  await wait('document.querySelector("[data-workflow-inspection-record=attempt_34]")')
  assert.equal(await read('document.querySelector("[data-workflow-workspace-code=call_34]").getAttribute("aria-pressed")'), 'true')
  assert.equal(await read('window.workflowFixture.workspaceQueries().at(-1).nodeId'), 'call_34')
  assert.equal(await read('window.workflowFixture.workspaceQueries().at(-1).kind'), 'attempts')
  assert.match(await read('document.querySelector("[data-workflow-inspection-record=attempt_34]").textContent'), /用量：精确.*输入 12.*输出 3.*费用 0\.25 usd/)
  assert.equal(await read('document.querySelector("[data-workflow-flow-node=call_34]").dataset.state'), 'unavailable', 'global graph pages must not pretend to contain an unread instance')
  await click('[data-workflow-flow-node=call_33]')
  await wait('document.querySelector("[data-workflow-inspection-record=attempt_33]")')
  assert.match(await read('document.querySelector("[data-workflow-inspection-record=attempt_33]").textContent'), /用量：未提供/)
  await click('[data-workflow-workspace-page=previous]')
  await wait('document.querySelectorAll("[data-workflow-workspace-code]").length === 32')
  await read('document.querySelector("[data-workflow-workspace-tab=run]").focus()')
  for (const type of ['keyDown', 'keyUp']) win.webContents.sendInputEvent({ type, keyCode: 'Right' })
  await wait('document.querySelector("[data-workflow-workspace-tab=plan]").getAttribute("aria-selected") === "true"')
  assert.equal(await read('Boolean(document.querySelector(".workflow-workspace-plan"))'), true)
  assert.equal(await read('Boolean(document.querySelector("[data-workflow-workspace-review]"))'), false, 'a blocked execution must not offer a fresh approval')
  await click('[data-workflow-workspace-tab=manage]')
  await wait('document.querySelector("[data-workflow-workspace-row=inspection-ui]")')
  assert.equal(await read('document.querySelectorAll("[data-workflow-workspace-row]").length'), 1)
  await click('[data-workflow-workspace-tab=templates]')
  await wait('document.querySelector(".workflow-template-catalog")')
  assert.equal(await read('document.querySelectorAll("[role=dialog]").length'), 1, 'embedded template editing must not stack another modal')
  await click('[data-workflow-workspace-tab=run]')
  await wait('document.querySelector("[data-workflow-classifier-result=classifier_record_0]") && document.querySelector("[data-workflow-flow-node=classifier_flag]")?.dataset.state === "completed"')
  assert.equal(await read('getComputedStyle(document.querySelector(".workflow-workspace-template-panel")).display'), 'none')
  const screenshots = {}
  for (const [name, width, height] of [['wide', 1280, 960], ['narrow', 430, 900]]) {
    win.setSize(width, height)
    await wait('innerWidth === ' + width)
    await read('new Promise(resolve => requestAnimationFrame(() => requestAnimationFrame(resolve)))')
    const bounds = await read('(() => { const node = document.querySelector(".workflow-workspace"); const r=node.getBoundingClientRect(); return {left:r.left,right:r.right,width:innerWidth,client:node.clientWidth,scroll:node.scrollWidth} })()')
    assert.ok(bounds.left >= 0 && bounds.right <= bounds.width, name + ' workspace must fit the viewport: ' + JSON.stringify(bounds))
    assert.ok(bounds.scroll <= bounds.client + 1, name + ' workspace must contain horizontal overflow')
    assert.equal(await read('Array.from(document.querySelectorAll(".workflow-workspace-tabs button")).every(node => { const r=node.getBoundingClientRect(); return r.left >= 0 && r.right <= innerWidth })'), true)
    const path = join(tmpdir(), `scry-workflow-workspace-${process.pid}-${name}.png`)
    await writeFile(path, (await win.webContents.capturePage()).toPNG())
    screenshots[name] = path
  }
  const framesBeforeRevision = await read('window.workflowFixture.workspaceFrameQueries().length')
  await read('window.workflowFixture.changeWorkspaceSource()')
  await wait('document.querySelector("[data-workflow-run-source]")?.dataset.workflowRunSource === "b".repeat(64) && document.querySelector(".workflow-run-canvas").textContent.includes("其他修订")')
  assert.equal(await read('document.querySelectorAll(".workflow-flow-node[data-state=completed]").length'), 0, 'same node IDs in another revision are not current-program execution evidence')
  assert.equal(await read('window.workflowFixture.workspaceFrameQueries().length'), framesBeforeRevision, 'unassociated revision records must not cause frame reads')
  await wait('document.querySelector(".workflow-run-evidence").textContent.includes("其他程序版本的记录")')
  win.setSize(1280, 960)
  await wait('innerWidth === 1280')
  await click('[data-workflow-workspace-tab=templates]')
  await wait('document.querySelector(".workflow-template-catalog button[aria-pressed]")?.disabled === false')
  await click('.workflow-template-catalog button[aria-pressed]')
  const openDraft = async () => {
    await wait('document.querySelector("[data-template-draft-id]")?.disabled === false')
    await click('[data-template-draft-id]')
    await wait('document.querySelector(".workflow-template-source")?.readOnly === false && !document.querySelector("[data-workflow-workspace-tab=plan]").disabled')
    assert.equal(await read('document.querySelector(".workflow-template-source").value'), '{}')
  }
  const editDraft = async text => {
    await click('.workflow-template-source')
    await win.webContents.insertText(text)
    await wait('document.querySelector(".workflow-template-source").value.includes(' + JSON.stringify(text) + ')')
    return read('document.querySelector(".workflow-template-source").value')
  }
  await openDraft()
  const unsaved = await editDraft('x')
  await click('[data-workflow-workspace-tab=plan]')
  await wait('document.querySelector(".workflow-workbench-confirm") && document.activeElement?.textContent === "当前编辑尚未保留"')
  assert.equal(await read('document.querySelector("[data-workflow-workspace-tab=templates]").getAttribute("aria-selected")'), 'true')
  await click('.workflow-workbench-confirm button:last-child')
  await wait('!document.querySelector(".workflow-workbench-confirm")')
  assert.equal(await read('document.querySelector(".workflow-template-source").value'), unsaved)
  await click('.workflow-template-embedded > .workflow-actions > button:first-child')
  await wait('document.querySelector(".workflow-workbench-confirm")')
  await click('.workflow-workbench-confirm button:nth-child(3)')
  await wait('document.querySelector(".workflow-template-catalog") && !document.querySelector(".workflow-template-source")')
  assert.equal(await read('document.querySelector("[data-workflow-workspace-tab=templates]").getAttribute("aria-selected")'), 'true', 'a cancelled Plan destination must not hijack a later Browse action')
  await openDraft()
  const beforeProjectChange = await editDraft('y')
  await read('window.workflowFixture.changeWorkspaceProject()')
  await wait('document.body.dataset.fixtureCwd === "/fixture-next" && document.querySelector(".workflow-workbench-confirm") && document.querySelector(".workflow-workspace").textContent.includes("项目已切换")')
  assert.equal(await read('document.querySelector(".workflow-template-source").value'), beforeProjectChange, 'project changes must not discard unsaved bytes')
  assert.equal(await read('document.querySelector(".workflow-workspace-context > code").textContent'), '/fixture')
  assert.equal(await read('document.querySelector("[data-workflow-workspace-tab=run]").disabled'), true)
  await click('.workflow-workbench-confirm button:last-child')
  await wait('!document.querySelector(".workflow-workbench-confirm")')
  assert.equal(await read('document.querySelector(".workflow-template-source").value'), beforeProjectChange)
  await click('[data-workflow-workspace-close]')
  await wait('document.querySelector(".workflow-workbench-confirm")')
  await click('.workflow-workbench-confirm button:nth-child(3)')
  await wait('!document.querySelector(".workflow-workspace")')
  assert.equal(await read('document.activeElement.hasAttribute("data-workflow-workspace-open")'), true)
  assert.equal(await read('document.querySelector("#parent-composer").value'), composer)
  assert.deepEqual(await read('structuredClone(window.workflowFixture.counters)'), before, 'inspection and navigation must not dispatch, approve, stop or reinject')
  assert.equal(win.isVisible(), false)
  return { workspace: true, scriptedBridge: true, nativeInput: true, dirtyNavigationGuard: true, projectChangePreservesDraft: true, framesOnDemand: true, linkedCodeAndGraph: true, boundedPages: [32, 9], preservedFalseAndZero: true, missingEvidenceNotZero: true, revisionIsolation: true, noReplay: true, focusRestored: true, screenshots }
}
