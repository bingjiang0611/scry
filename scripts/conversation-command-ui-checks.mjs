import assert from 'node:assert/strict'
import { checkConversationTemplateTaskUi } from './conversation-template-task-ui-checks.mjs'
import { checkWorkflowMessageChoiceUi } from './workflow-message-choice-ui-checks.mjs'
import { writeFile } from 'node:fs/promises'
import { join } from 'node:path'

/** Isolated real ConversationView/React/Chromium input. The bridge is scripted;
 * these checks do not stand in for production Main or Provider execution. */
export async function checkConversationCommandUi(win, temp) {
  const read = expression => win.webContents.executeJavaScript(expression)
  const wait = expression => read(`(async()=>{const end=performance.now()+5000;while(!(${expression})){if(performance.now()>end)throw Error(${JSON.stringify(expression)});await new Promise(resolve=>requestAnimationFrame(resolve))}return true})()`)
  const frame = () => read('new Promise(resolve=>requestAnimationFrame(()=>requestAnimationFrame(resolve)))')
  const click = async selector => {
    const point = await read(`(()=>{const e=document.querySelector(${JSON.stringify(selector)});if(!e||e.disabled)throw Error('missing/disabled control');e.scrollIntoView({block:'center'});const r=e.getBoundingClientRect(),x=Math.round(r.x+r.width/2),y=Math.round(r.y+r.height/2);if(!e.contains(document.elementFromPoint(x,y)))throw Error('control not hit-testable');return{x,y}})()`)
    for (const type of ['mouseDown', 'mouseUp']) win.webContents.sendInputEvent({ type, ...point, button: 'left', clickCount: 1 })
  }
  const key = (keyCode, modifiers = []) => {
    for (const type of ['keyDown', 'keyUp']) win.webContents.sendInputEvent({ type, keyCode, modifiers })
  }
  const type = async text => {
    await click('textarea[aria-label="描述任务"]')
    // Hidden fixture windows do not apply the OS application's Select All
    // accelerator. Use Electron's native editing command, not DOM value writes.
    win.webContents.selectAll()
    await frame()
    await writeFile(join(temp, 'last-input-boundary.json'), JSON.stringify(await read('(()=>{const e=document.querySelector("textarea[aria-label=描述任务]");return {draft:window.conversationCommandFixture.draft(),value:e.value,selection:[e.selectionStart,e.selectionEnd],focused:document.activeElement===e}})()'), null, 2))
    await wait('(()=>{const e=document.querySelector("textarea[aria-label=描述任务]");return document.activeElement===e && e.selectionStart===0 && e.selectionEnd===e.value.length})()')
    await win.webContents.insertText(text)
    await wait(`window.conversationCommandFixture.draft()===${JSON.stringify(text)}`)
  }
  const queue = outcome => read(`window.conversationCommandFixture.outcomes.push(${JSON.stringify(outcome)})`)
  const capturedSubmission = { reference: { conversationId: '00000000-0000-4000-8000-000000000001', commandId: 'fixture-run' }, planningCommandId: 'fixture-planning',
    size: { state: 'available', snapshot: { value: 'medium', source: 'default', fingerprint: '0'.repeat(64) }, readAt: 1 } }
  const snapshot = () => read('JSON.parse(JSON.stringify(window.conversationCommandFixture.calls))')
  const send = () => click('button.send')
  const menu = '.conversation-commands details'
  const open = async () => {
    if (!await read(`document.querySelector('${menu}').open`)) await click(`${menu} > summary`)
    await wait('document.querySelectorAll(".conversation-command-row").length>0')
  }
  const chooseScry = async () => {
    await open()
    await click('.conversation-command-row')
    await wait('!document.querySelector(".conversation-commands details").open && document.activeElement===document.querySelector("textarea[aria-label=描述任务]")')
    assert.equal(await read('document.querySelector(".conversation-message-choice").disabled'), true, 'explicit command selection takes precedence over a one-message choice')
  }
  await wait('document.querySelector(".unified-conversation") && !document.querySelector("textarea").disabled')
  await read('document.addEventListener("click",event=>{document.body.dataset.lastTrustedClick=String(event.isTrusted)},true)')
  assert.equal((await snapshot()).metadata.length, 0, 'mount must not discover native commands')
  assert.equal((await snapshot()).taskLists.length, 0, 'closed task disclosure must not read task records')
  await chooseScry()
  assert.deepEqual((await snapshot()).metadata, [null], 'known metadata must not request a native target')
  await type('/scry-workflow size small')
  await queue({ kind: 'control', commandId: 'fixture-size', action: 'size_updated', snapshot: { value: 'small', source: 'preference', fingerprint: '0'.repeat(64) } })
  await send()
  await wait('window.conversationCommandFixture.draft()==="" && document.body.textContent.includes("规模建议已更新")')
  assert.equal((await snapshot()).previews, 0, 'settings must not prepare a native run')
  assert.equal((await snapshot()).plans, 0)
  await chooseScry()
  await type('/scry-workflow list')
  await queue({ kind: 'control', commandId: 'fixture-list', action: 'open_workflows' })
  await send()
  await wait('document.querySelector(".workflow-workbench[role=dialog]") && window.conversationCommandFixture.calls.catalogs===1')
  assert.equal((await snapshot()).plans, 0, 'management must not generate a plan')
  key('Escape')
  await wait('!document.querySelector(".workflow-workbench")')
  await type('/scry-workflow invalid')
  await queue({ kind: 'needs_native_context' })
  await queue({ kind: 'needs_command_source', catalog: await read('window.conversationCommandFixture.known') })
  await send()
  await wait('document.querySelector(".conversation-commands details").open && !document.querySelector(".conversation-recovery")')
  let calls = await snapshot()
  assert.equal(calls.submissions.at(-1).commandId, calls.submissions.at(-2).commandId, 'negotiation must preserve command identity')
  assert.equal(calls.previews, 1)
  assert.deepEqual(calls.metadata, [null], 'source-required response must not launch another discovery')
  await chooseScry()
  await queue({ kind: 'rejected', error: 'synthetic command refused' })
  await send()
  await wait('document.body.textContent.includes("synthetic command refused")')
  assert.equal(await read('window.conversationCommandFixture.draft()'), '/scry-workflow invalid')
  assert.equal(await read('Boolean(document.querySelector(".conversation-recovery"))'), false, 'known rejection must not become an unknown-write lock')
  await type('/scry-workflow run preserve this goal')
  await queue({ kind: 'control', commandId: 'fixture-run', action: 'open_workflow_planner', command: '/scry-workflow run preserve this goal', workspace: '/synthetic/command-ui', submission: capturedSubmission })
  await send()
  await wait('document.querySelector(".workflow-modal") && document.querySelector("button[data-workflow-action=plan]") && !document.querySelector("button[data-workflow-action=plan]").disabled')
  assert.equal((await snapshot()).plans, 0, 'opening configuration must not use the legacy callback')
  assert.equal(await read('document.querySelector(".workflow-goal textarea").disabled'), true, 'captured goal must be read only')
  assert.equal(await read('document.querySelector(".workflow-size-recorded").textContent'), await read('window.conversationCommandFixture.expectedCapturedSize'), 'captured size and source must use the recorded localized labels')
  assert.equal(await read('document.querySelector(".workflow-modal .workflow-size-setting")===null'), true, 'captured configuration must not edit current global size preferences')
  assert.equal(await read('document.querySelector("button[data-workflow-action=reconfigure]")===null'), true, 'captured preview cannot reconfigure')
  assert.equal((await snapshot()).workflowPlans.length, 0, 'opening configuration must not plan')
  await click('button[data-workflow-action=plan]')
  await wait('window.conversationCommandFixture.calls.workflowPlans.length===1 && document.querySelector("button[data-workflow-action=review]")')
  await click('button[data-workflow-action=review]')
  await wait('document.querySelector("button[data-workflow-action=approve]")')
  const workflowPlan = (await snapshot()).workflowPlans[0]
  assert.equal(workflowPlan.command, '/scry-workflow run preserve this goal', 'planning must preserve Main command')
  assert.equal(workflowPlan.commandId, 'fixture-planning', 'planning must preserve stable planning identity')
  assert.deepEqual(workflowPlan.submission, capturedSubmission.reference, 'planning must preserve captured reference')
  assert.equal(await read('window.conversationCommandFixture.draft()'), '/scry-workflow run preserve this goal', 'opening configuration must retain the goal')
  await click('.workflow-modal .workflow-actions > button:first-child')
  await wait('!document.querySelector(".workflow-modal")')
  const templateTasks = await checkConversationTemplateTaskUi(win, temp, { read, wait, click, key, type, queue, send, frame, snapshot })
  await type('/scry-workflow direct exact original input')
  await queue({ kind: 'needs_native_context' })
  await queue({ kind: 'direct', runId: 'fixture-direct', disposition: 'created' })
  await send()
  await wait('window.conversationCommandFixture.draft()===""')
  calls = await snapshot()
  assert.equal(calls.submissions.at(-1).prompt, '/scry-workflow direct exact original input')
  assert.equal(calls.submissions.at(-1).selectedCommandId, 'scry:workflow')
  assert.equal(calls.submissions.at(-1).message.confirmFresh, true)
  await type('preserve unknown input')
  await queue({ kind: 'needs_native_context' })
  await read('window.conversationCommandFixture.outcomes.push(new Error("synthetic lost ACK"))')
  await send()
  await wait('document.querySelector(".conversation-recovery") && document.body.textContent.includes("不会自动重发")')
  const beforeRetry = await snapshot()
  const unknownRequest = beforeRetry.submissions.at(-1)
  await frame()
  assert.equal((await snapshot()).submissions.length, beforeRetry.submissions.length, 'unknown result must not retry itself')
  assert.equal(await read('window.conversationCommandFixture.draft()'), 'preserve unknown input')
  await queue({ kind: 'direct', runId: 'fixture-readback', disposition: 'duplicate' })
  await click('.conversation-recovery button')
  await wait('window.conversationCommandFixture.draft()==="" && !document.querySelector(".conversation-recovery")')
  assert.deepEqual((await snapshot()).submissions.at(-1), unknownRequest, 'explicit readback must reuse the full frozen request')
  const messageChoice = await checkWorkflowMessageChoiceUi({ read, wait, click, key, type, queue, snapshot, send, capturedSubmission })
  await open()
  await read('window.conversationCommandFixture.holdMetadata()')
  await click('.conversation-command-menu > button:first-of-type')
  await wait('window.conversationCommandFixture.calls.metadata.length===2')
  await read('window.conversationCommandFixture.scope("pi:0000000000000001")')
  await frame()
  await read('window.conversationCommandFixture.releaseMetadata()')
  await frame()
  await open()
  assert.equal(await read('document.body.textContent.includes("stale-native-command")'), false, 'stale native result must not cross a scope change')
  key('Escape')
  await wait('!document.querySelector(".conversation-commands details").open')
  assert.equal(await read('document.activeElement===document.querySelector(".conversation-commands summary")'), true)
  await open()
  await writeFile(join(temp, 'commands-wide.png'), (await win.webContents.capturePage()).toPNG())
  win.setSize(430, 900)
  await wait('innerWidth===430')
  await frame()
  assert.equal(await read('document.documentElement.scrollWidth<=innerWidth'), true, 'command controls must not overflow the viewport')
  assert.equal(await read('(()=>{const r=document.querySelector(".conversation-command-menu").getBoundingClientRect();return r.left>=0 && r.right<=innerWidth})()'), true)
  assert.equal(await read('document.body.dataset.lastTrustedClick'), 'true')
  await writeFile(join(temp, 'commands-narrow.png'), (await win.webContents.capturePage()).toPNG())
  key('Escape')
  await wait('!document.querySelector(".conversation-commands details").open')
  const taskMenu = '.conversation-workflow-tasks'
  const taskSelector = digit => `[data-workflow-task="submission-${digit.repeat(64)}"]`
  const taskBaseline = await snapshot()
  await click(`${taskMenu} > summary`)
  await wait('document.querySelectorAll(".conversation-task-list li").length===2')
  assert.equal(await read('document.activeElement===document.querySelector(".conversation-task-actions button")'), true, 'task disclosure must move keyboard focus inside')
  await click(taskSelector('1'))
  await wait('document.querySelector(".conversation-task-inspector [data-workflow-task-open]")')
  assert.equal(await read('document.querySelector(".conversation-task-input").textContent'), '/scry-workflow run original captured goal')
  await click('[data-workflow-task-open]')
  await wait('document.querySelector(".workflow-goal textarea")')
  assert.equal(await read('document.querySelector(".workflow-goal textarea").disabled'), true)
  assert.equal((await snapshot()).workflowPlans.length, taskBaseline.workflowPlans.length, 'reopening configuration must not plan')
  key('Escape')
  await wait('!document.querySelector(".workflow-modal")')
  await click(`${taskMenu} > summary`)
  await wait('document.querySelectorAll(".conversation-task-list li").length===2')
  await click(taskSelector('2'))
  await wait('document.querySelector(".conversation-task-inspector")')
  assert.equal(await read('document.querySelector(".conversation-task-inspector [data-workflow-task-open]")===null'), true, 'completed root must remain read only')
  assert.equal(await read('document.querySelector(".conversation-task-inspector").textContent.includes("派发结果未知")'), true, 'known plan must not upgrade unknown task intake')
  key('Escape')
  await wait('!document.querySelector(".conversation-task-inspector")')
  await frame()
  assert.equal(await read(`document.activeElement===document.querySelector('${taskSelector('2')}')`), true, 'closing inspection must restore focus to its task row')
  await read('window.conversationCommandFixture.observeReady()')
  await click(taskSelector('2'))
  await wait('document.querySelector("[data-workflow-task-open]")')
  await click('[data-workflow-task-open]')
  await wait('document.querySelector("button[data-workflow-action=approve]")')
  assert.equal((await snapshot()).workflowPlans.length, taskBaseline.workflowPlans.length, 'opening known preview must not replan')
  await click('.workflow-modal .workflow-actions > button:first-child')
  await wait('!document.querySelector(".workflow-modal")')
  await click(`${taskMenu} > summary`)
  await wait('document.querySelectorAll(".conversation-task-list li").length===2')
  await click('.conversation-task-actions button:last-child')
  await wait('document.querySelectorAll(".conversation-task-list li").length===1')
  assert.equal((await snapshot()).taskLists.at(-1).cursor, 'synthetic-next')
  await click(taskSelector('3'))
  await wait('document.querySelector(".conversation-task-inspector")')
  assert.equal(await read('document.querySelector("[data-workflow-task-open]")===null'), true, 'interrupted capture must not reopen planning')
  key('Escape')
  await wait('!document.querySelector(".conversation-task-inspector")')
  await read('window.conversationCommandFixture.failTaskList()')
  await click('.conversation-task-actions button:first-child')
  await wait('document.querySelector(".conversation-task-menu [role=alert]")')
  assert.equal(await read('document.querySelectorAll(".conversation-task-list li").length'), 1, 'read failure must retain the previously observed page')
  await click('.conversation-task-actions button:first-child')
  await wait('document.querySelectorAll(".conversation-task-list li").length===2 && !document.querySelector(".conversation-task-menu [role=alert]")')
  assert.equal(await read('(()=>{const r=document.querySelector(".conversation-task-menu").getBoundingClientRect();return r.left>=0 && r.right<=innerWidth})()'), true, 'task menu must fit the narrow desktop viewport')
  await frame()
  await writeFile(join(temp, 'tasks-narrow.png'), (await win.webContents.capturePage()).toPNG())
  await read('window.conversationCommandFixture.holdTaskInspection()')
  const beforeLateInspection = (await snapshot()).taskInspections.length
  await click(taskSelector('1'))
  await wait(`window.conversationCommandFixture.calls.taskInspections.length===${beforeLateInspection + 1}`)
  await read('window.conversationCommandFixture.conversation("00000000-0000-4000-8000-000000000002")')
  await wait('!document.querySelector(".conversation-workflow-tasks").open')
  await read('window.conversationCommandFixture.releaseTaskInspection()')
  await frame()
  assert.equal(await read('document.querySelector(".conversation-task-inspector")===null && !document.querySelector(".conversation-workflow-tasks").open'), true, 'late inspection must not cross conversation scope')
  const taskFinal = await snapshot()
  assert.equal(taskFinal.workflowPlans.length, taskBaseline.workflowPlans.length)
  assert.equal(taskFinal.metadata.length, taskBaseline.metadata.length, 'task observation must not discover native metadata')
  assert.equal(taskFinal.submissions.length, taskBaseline.submissions.length, 'task observation must not resubmit chat input')
  return { templateTasks, messageChoice, taskObservationAndReopen: true, taskUnknownNotUpgraded: true, taskPaginationAndReadFailure: true,
    taskScopeFence: true, knownMetadataWithoutNative: true, sourceRequiredNotUnknown: true, managementActuallyOpened: true,
    settingsWithoutNativePreparation: true, plannerConfigurationCallbackOnly: true, rawDirectInputPreserved: true,
    unknownRetainedWithoutReplay: true, staleMetadataFenced: true, trustedPointerInput: true,
    escapeFocus: true, narrowNoOverflow: true, calls: await snapshot() }
}
