import assert from 'node:assert/strict'
import { writeFile } from 'node:fs/promises'

/** Native pointer/keyboard UI checks; the bridge is explicitly scripted, not Provider evidence. */
export async function checkWorkflowOutputInspection({ read, wait, click, win }) {
  const counters = await read('JSON.stringify(window.workflowFixture.counters)')
  const key = code => { for (const type of ['keyDown', 'keyUp']) win.webContents.sendInputEvent({ type, keyCode: code }) }
  const output = '.workflow-output-inspector'
  const action = name => `${output} [data-workflow-output-action=${name}]`
  const row = (id, kind) => `[data-workflow-inspection-record=${id}] [data-workflow-inspection-output=${kind}]`
  const close = async () => { key('Escape'); await wait(`!document.querySelector('${output}')`) }
  win.setSize(1280, 960)
  await wait('innerWidth === 1280')
  const generation = await read('Number(document.querySelector("[data-workflow-fixture-generation]").dataset.workflowFixtureGeneration)')
  await read('window.workflowFixture.installOutputInspection()')
  await wait(`Number(document.querySelector('[data-workflow-fixture-generation]').dataset.workflowFixtureGeneration)>${generation}`)
  await click('[data-workflow-id=inspection-ui] summary')
  await click('[data-workflow-inspection-open=inspection-ui]')
  await wait('document.querySelectorAll("[data-workflow-program-node]").length === 32')
  await click('[data-workflow-inspection-tab=history]')
  await wait('document.querySelectorAll("[data-workflow-inspection-record]").length === 32')
  assert.equal(await read('window.workflowFixture.outputQueries().length'), 0, 'metadata must not fetch bodies')
  await click(row('attempt_1', 'attempt'))
  await wait(`document.querySelector('${output} textarea')?.value.length === 8191`)
  assert.equal(await read(`document.querySelector('${output} textarea').readOnly`), true)
  await click(action('next'))
  await wait(`document.querySelector('${output} textarea')?.value.startsWith('😀')`)
  assert.deepEqual(await read('window.workflowFixture.outputQueries().at(-1)'), {
    workflowId: 'inspection-ui', programRevision: 'a'.repeat(64), selection: { kind: 'attempt', attemptId: 'attempt_1' }, offset: 8191, expectedContentHash: 'c'.repeat(64)
  })
  await read('window.workflowFixture.failOutput()')
  await click(action('next'))
  await wait(`document.querySelector('${output} [role=alert]')?.textContent.includes('Fixture read interrupted')`)
  await click(action('previous'))
  await wait(`document.querySelector('${output} textarea')?.value.startsWith('😀')`)
  assert.equal(await read('window.workflowFixture.outputQueries().at(-1).expectedContentHash'), 'c'.repeat(64))
  await read('window.workflowFixture.failOutput()')
  await click(action('next'))
  await wait(`document.querySelector('${output} [role=alert]')?.textContent.includes('Fixture read interrupted')`)
  await click(action('refresh'))
  await wait(`document.querySelector('${output} textarea')?.value === 'END_RECORDED_OUTPUT'`)
  assert.equal(await read('window.workflowFixture.outputQueries().at(-1).expectedContentHash'), 'c'.repeat(64))
  await read('window.workflowFixture.changeOutput()')
  await click(action('refresh'))
  await wait(`document.querySelector('${output} [role=status]')?.textContent.includes('输出内容已变化')`)
  await click(action('refresh'))
  await wait(`document.querySelector('${output} textarea')?.value.length === 8191`)
  assert.equal(await read('window.workflowFixture.outputQueries().at(-1).offset'), 0)
  assert.equal(await read('window.workflowFixture.outputQueries().at(-1).expectedContentHash'), undefined)
  assert.equal(await read(`document.querySelector('${action('previous')}').disabled`), true)
  await close()
  assert.equal(await read('document.activeElement.dataset.workflowInspectionOutput'), 'attempt')
  await click(row('attempt_2', 'attempt'))
  await wait(`document.querySelector('${output} [role=status]')?.textContent === '未记录输出'`)
  assert.equal(await read(`document.querySelector('${output} textarea') === null`), true)
  await close()
  await click(row('attempt_3', 'attempt'))
  await wait(`document.querySelector('${output} [role=status]')?.textContent.startsWith('结果未知')`)
  win.setSize(430, 900)
  await wait('innerWidth === 430')
  await read('new Promise(resolve=>requestAnimationFrame(()=>requestAnimationFrame(resolve)))')
  const contained = `(() => { const e=document.querySelector('${output}'); const r=e.getBoundingClientRect(); return r.left>=0 && r.right<=innerWidth && e.scrollWidth<=e.clientWidth+1 })()`
  assert.equal(await read(contained), true, 'bounded unknown reason must wrap at 430px')
  await close()
  await click('[data-workflow-inspection-frame=frame_0]')
  await wait('document.querySelector("[data-workflow-frame=frame_0]")')
  await click('[data-workflow-frame-output=frame_0]')
  await wait(`document.querySelector('${output} textarea')?.value === '{"frame":"frame_0"}'`)
  const count = await read('window.workflowFixture.outputQueries().length')
  const render = await read('Number(document.body.dataset.workflowFixtureRender)')
  await read('window.workflowFixture.rerenderInspection()')
  await wait(`Number(document.body.dataset.workflowFixtureRender)>${render}`)
  assert.equal(await read('window.workflowFixture.outputQueries().length'), count, 'streaming parent render must not reread an identical selector')
  assert.equal(await read(contained), true, 'output metadata and body must fit at 430px')
  const contrast = await read(`(() => {
    const e=document.querySelector('${output}'), values=c=>c.match(/[\\d.]+/g).map(Number)
    const lum=rgb=>rgb.slice(0,3).map(v=>v/255).map(v=>v<=.04045?v/12.92:((v+.055)/1.055)**2.4).reduce((sum,v,i)=>sum+v*[.2126,.7152,.0722][i],0)
    const bg=lum(values(getComputedStyle(e).backgroundColor)), fg=lum(values(getComputedStyle(e.querySelector('textarea')).color))
    return { ratio:(Math.max(bg,fg)+.05)/(Math.min(bg,fg)+.05), padding:parseFloat(getComputedStyle(e).paddingLeft) }
  })()`)
  assert.ok(contrast.ratio >= 4.5, JSON.stringify(contrast))
  assert.ok(contrast.padding >= 16)
  await read(`document.querySelector('${action('refresh')}').focus()`)
  key('Tab')
  await wait('document.activeElement.dataset.workflowOutputAction === "close"')
  for (const type of ['keyDown', 'keyUp']) win.webContents.sendInputEvent({ type, keyCode: 'Tab', modifiers: ['shift'] })
  await wait('document.activeElement.dataset.workflowOutputAction === "refresh"')
  await writeFile('/tmp/scry-workflow-output-ui-narrow.png', (await win.webContents.capturePage()).toPNG())
  await close()
  assert.equal(await read('Boolean(document.querySelector(".workflow-frame-inspector")) && document.activeElement.dataset.workflowFrameOutput === "frame_0"'), true)
  key('Escape')
  await wait('!document.querySelector(".workflow-frame-inspector") && document.activeElement.dataset.workflowInspectionFrame === "frame_0"')
  win.setSize(1280, 960)
  await wait('innerWidth === 1280')
  await click('[data-workflow-inspection-kind=systems]')
  await wait('document.querySelector("[data-workflow-inspection-record=recorded-check]")')
  await click(row('recorded-check', 'stdout'))
  await wait(`document.querySelector('${output} textarea')?.value === 'RECORDED_FIXTURE_STDOUT'`)
  assert.equal(await read(`document.querySelector('${output}').textContent.includes('记录可能不完整')`), true)
  assert.equal(await read(`document.querySelectorAll('${output} dd code')[1].textContent`), 'b'.repeat(64))
  await close()
  await click(row('recorded-check', 'stderr'))
  await wait(`document.querySelector('${output} [role=status]')?.textContent === '已记录为空内容'`)
  assert.equal(await read(`document.querySelector('${output} textarea') === null`), true)
  await close()
  await click(row('recorded-check', 'result'))
  await wait(`document.querySelector('${output} textarea')?.value === '{"state":"stopped","passed":false}'`)
  await close()
  await read('window.workflowFixture.changeInspectionSource()')
  await click(row('recorded-check', 'stdout'))
  await wait(`document.querySelector('${output} [role=status]')?.textContent.includes('程序已变化')`)
  assert.equal(await read(`document.querySelector('${output} textarea') === null`), true)
  await close()
  key('Escape')
  await wait('!document.querySelector(".workflow-execution-inspector")')
  assert.equal(await read('JSON.stringify(window.workflowFixture.counters)'), counters)
  return { scriptedBridge: true, metadataLazy: true, unicodePaging: true, pinnedRetryAndBack: true, changedBodyRestarts: true,
    emptyMissingUnknownDistinct: true, frameResult: true, parentRerenderNoRead: true, nativeFocusEscapeTab: true,
    olderSourcePreserved: true, captureTruncationShown: true, sourceChangeRefused: true, narrowLayout: true, contrast, noMutations: true }
}
